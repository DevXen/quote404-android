def main():
    nums = [int(l.strip()) for l in open(FIXLIST, encoding='utf-8') if l.strip()]
    assert len(nums) == 83 and len(set(nums)) == 83, "fix list must have 83 unique numbers"
    assert set(nums) == set(R.keys()), "replacement map must cover exactly the fix list"
    conn = sqlite3.connect('file:%s?mode=ro' % DB, uri=True)
    out_lines = []
    for n in nums:
        src = conn.execute("SELECT text FROM quotes WHERE number=?", (n,)).fetchone()[0]
        reps = list(R[n])
        count = src.count('�')
        assert count == len(reps), f"quote {n}: found {count} damaged chars but have {len(reps)} replacements"
        # Build repaired string AND verify only damaged positions change.
        # Walk source; at each � consume one replacement (may be '' = drop).
        parts, ri = [], 0
        for ch in src:
            if ch == '�':
                parts.append(reps[ri]); ri += 1
            else:
                parts.append(ch)
        assert ri == len(reps)
        sv = ''.join(parts)
        assert '�' not in sv, f"quote {n}: damage remains"
        # Structural check: re-derive by masking; every non-damaged char must match.
        j = 0
        for ch in src:
            if ch == '�':
                rep = reps[0]; reps.pop(0)
                assert sv[j:j+len(rep)] == rep, f"quote {n}: replacement mismatch at offset {j}"
                j += len(rep)
            else:
                assert sv[j] == ch, f"quote {n}: non-damaged char changed at offset {j}"
                j += 1
        assert j == len(sv)
        assert '\n' in sv or True
        out_lines.append(json.dumps({'n': n, 'sv': sv}, ensure_ascii=False))
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(out_lines) + '\n')
    print(f"wrote {len(out_lines)} lines to {OUT}")

if __name__ == '__main__':
    main()
